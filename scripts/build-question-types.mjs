#!/usr/bin/env node
// Reads src/protectedTestContent.mjs and writes src/questionTypes.mjs: for every built-in test, which
// Reading questions are TRUE/FALSE/NOT GIVEN ("tfng") and which are YES/NO/NOT GIVEN ("ynng"), taken
// from each block's own instructions. Run again whenever test content changes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(path.join(root, "src/protectedTestContent.mjs"), "utf8");
const lines = src.split("\n");
const starts = [];
lines.forEach((l, i) => { const m = l.match(/^const test(\d+) = \{/); if (m) starts.push([Number(m[1]), i]); });
const factoryOf = {};
lines.forEach((l, i) => { const m = l.match(/^const (readingLegacyFactory\d+) = function/); if (m) factoryOf[m[1]] = i; });

const out = {};
starts.forEach(([n, i], k) => {
  let block = lines.slice(i, k + 1 < starts.length ? starts[k + 1][1] : lines.length).join("\n");
  const legacy = block.match(/legacyFactory:\s*(readingLegacyFactory\d+)/);
  if (legacy && factoryOf[legacy[1]] !== undefined) {
    const fi = factoryOf[legacy[1]];
    const end = lines.findIndex((l, j) => j > fi && /^};?\s*$/.test(l));
    block = lines.slice(fi, end > fi ? end : fi + 400).join("\n");
  } else {
    const r = block.search(/\n\s*"?reading"?\s*:/);
    block = r >= 0 ? block.slice(r) : block;
  }
  // Split into blocks at each task start, then classify by its instruction wording.
  const pieces = block.split(/(?=\btype"?\s*:\s*"|renderTFNGBlock\(|renderMCQBlock\(|renderSentenceGapsBlock\(|renderHeadingsTask\(|renderShortAnswerBlock\(|renderEndingsMatchBlock\(|renderSummarySelectBlock\(|renderNotesBlock\()/);
  const types = {};
  pieces.forEach((p) => {
    const ynng = /\bYES\b[^"]{0,20}if the statement/i.test(p) || /YES\s*\/\s*NO\s*\/\s*NOT GIVEN/i.test(p) || /"YES",\s*"NO",\s*"NOT GIVEN"/i.test(p) || /claims of the writer|views of the writer|writer's claims|writer's views/i.test(p);
    const tfng = /\bTRUE\b[^"]{0,20}if the statement/i.test(p) || /TRUE\s*\/\s*FALSE\s*\/\s*NOT GIVEN/i.test(p) || /"TRUE",\s*"FALSE",\s*"NOT GIVEN"/i.test(p) || /agree with the information/i.test(p);
    const kind = ynng && !tfng ? "ynng" : tfng && !ynng ? "tfng" : "";
    if (!kind) return;
    const qs = [...p.matchAll(/"?\bq"?\s*:\s*(\d+)/g)].map((m) => Number(m[1]));
    const range = p.match(/Questions?\s+(\d+)\s*[-–]\s*(\d+)/i);
    const all = qs.length ? qs : (range ? Array.from({ length: Number(range[2]) - Number(range[1]) + 1 }, (_, x) => Number(range[1]) + x) : []);
    all.forEach((q) => { if (q >= 1 && q <= 40) types[q] = kind; });
  });
  if (Object.keys(types).length) out[`ielts${n}`] = { reading: types };
});
const body = `// Generated by scripts/build-question-types.mjs from src/protectedTestContent.mjs. Do not edit by hand.\nexport const QUESTION_TYPES = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(path.join(root, "src/questionTypes.mjs"), body);
const count = Object.values(out).reduce((s, t) => s + Object.keys(t.reading).length, 0);
console.log(`Wrote src/questionTypes.mjs: ${Object.keys(out).length} tests, ${count} TRUE/FALSE or YES/NO questions.`);
